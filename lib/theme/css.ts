import { NEUTRALS, type Mode } from './tokens.ts';
import { ACCENT_TOKENS, CAMPUSOS_PALETTE, type AccentPalette } from './palette.ts';

// Builds app/theme.css. Run `pnpm theme:css` after changing lib/theme/*; tests fail if the file is stale.
//
// How modes and palettes combine:
// - <html data-theme="light|dark"> selects the fixed tokens (set before first paint by lib/theme/boot.ts).
// - A school palette is applied as inline custom properties on <html>: --al-<token> (light) and --ad-<token>
//   (dark). Each accent token falls back to the CampusOS value when those are absent, so switching appearance
//   never needs JavaScript to recompute colors, and removing the properties restores the CampusOS palette.
// - Without JavaScript the operating-system preference still applies (prefers-color-scheme).
// - Printing always uses the light tokens.

const fixed = (mode: Mode) => Object.entries(NEUTRALS[mode]).filter(([k]) => k !== 'ink').map(([k, v]) => `--${k}:${v}`);
const accent = (mode: Mode, palette: AccentPalette = CAMPUSOS_PALETTE) => ACCENT_TOKENS.map(t => `--${t}:var(--a${mode[0]}-${t},${palette[mode][t]})`);
const derived = [
    '--surface-translucent:color-mix(in srgb,var(--surface) 94%,transparent)',
    '--focus-glow:color-mix(in srgb,var(--focus-ring) 18%,transparent)',
    '--brand-line:color-mix(in srgb,var(--on-brand) 12%,transparent)',
    '--brand-tint:color-mix(in srgb,var(--on-brand) 8%,transparent)',
];
const block = (mode: Mode) => [`color-scheme:${mode}`, ...fixed(mode), ...accent(mode), ...derived].join(';');

/** Custom properties that apply a palette to <html> (both modes at once). */
export function paletteProperties(palette: AccentPalette): Record<string, string> {
    const out: Record<string, string> = {};
    for (const mode of ['light', 'dark'] as const) for (const t of ACCENT_TOKENS) out[`--a${mode[0]}-${t}`] = palette[mode][t];
    return out;
}

export function themeCss(): string {
    return [
        '/* Generated by lib/theme/css.ts (pnpm theme:css). Do not edit by hand. */',
        `:root,:root[data-theme=light]{${block('light')}}`,
        `:root[data-theme=dark]{${block('dark')}}`,
        `@media (prefers-color-scheme:dark){:root:not([data-theme]){${block('dark')}}}`,
        `@media print{:root,:root[data-theme]{${block('light')}}}`,
        '',
    ].join('\n');
}
